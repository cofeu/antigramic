#!/usr/bin/env python3
"""Bake antialiased 2-bit glyph masks from the bundled DejaVu Sans font."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[2]
FONT_PATH = ROOT / "assets/fonts/DejaVuSans.ttf"
OUTPUT_PATH = ROOT / "kernel/ui/font_data.h"
CODEPOINTS = list(range(32, 127)) + [
    ord(char) for char in "ÇĞİÖŞÜçğıöşü°·"
]
SIZES = (24, 32)


def packed_mask(mask):
    result = bytearray()
    value = 0
    used = 0
    for alpha in mask:
        value = (value << 2) | min(3, (alpha * 3 + 127) // 255)
        used += 1
        if used == 4:
            result.append(value)
            value = 0
            used = 0
    if used:
        result.append(value << (2 * (4 - used)))
    return result


def make_font(size):
    font = ImageFont.truetype(str(FONT_PATH), size=size)
    ascent, line_height_extra = font.getmetrics()
    metrics = []
    data = bytearray()
    for codepoint in CODEPOINTS:
        char = chr(codepoint)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width = max(0, right - left)
        height = max(0, bottom - top)
        mask = Image.new("L", (max(1, width), max(1, height)), 0)
        ImageDraw.Draw(mask).text((-left, -top), char, font=font, fill=255, anchor="ls")
        packed = packed_mask(mask.tobytes()) if width and height else bytearray()
        metrics.append((codepoint, round(font.getlength(char)), left, top, width, height, len(data)))
        data.extend(packed)
    return ascent, line_height_extra, metrics, data


def format_array(values, per_line=16):
    lines = []
    for start in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in values[start:start + per_line]))
    return ",\n".join(lines)


def main():
    output = [
        "/* Generated by gen_font.py. Do not edit by hand. */",
        "#ifndef _KERNEL_UI_FONT_DATA_H",
        "#define _KERNEL_UI_FONT_DATA_H",
        "#include <stdint.h>",
        "typedef struct { uint16_t codepoint, advance; int16_t left, top; uint8_t width, height; uint32_t offset; } ui_glyph_t;",
    ]
    for size in SIZES:
        ascent, line_height, glyphs, data = make_font(size)
        output.append(f"#define UI_FONT_{size}_ASCENT {ascent}")
        output.append(f"#define UI_FONT_{size}_LINE_HEIGHT {ascent + line_height}")
        output.append(f"static const ui_glyph_t ui_font_{size}_glyphs[] = {{")
        output.extend(
            f"    {{{cp}, {advance}, {left}, {top}, {width}, {height}, {offset}}},"
            for cp, advance, left, top, width, height, offset in glyphs
        )
        output.append("};")
        output.append(f"static const uint8_t ui_font_{size}_data[] = {{\n{format_array(data)}\n}};")
    output.append("#endif")
    OUTPUT_PATH.write_text("\n".join(output) + "\n")


if __name__ == "__main__":
    main()
